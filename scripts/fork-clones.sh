#!/usr/bin/env bash
# Reports which of the person's copies of shipped mods and layouts (cloned_from), and which of
# their own mods, are affected by the fork update to <version>, and which files the merge of that tag
# will conflict in. Run it before the merge: it previews the merge with git merge-tree and changes
# nothing in the checkout. After the merge it compares against the merged HEAD instead.
#
#   scripts/fork-clones.sh 0.1.18
#
# Writes .cache/fork-update-v<version>/clones.md for the update agent; it changes nothing else.
# Profiles: HERDR_PROFILES (space separated), default ~/.config/herdr-app and ~/.config/herdr-app-personal.
# Exit codes: 0 report written (copies needing review is not an error), 1 it could not run.
# Works with macOS's bash 3.2. See docs/fork-update-copies.md.
set -euo pipefail

version="${1:-}"
version="${version#v}"
if ! [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "usage: scripts/fork-clones.sh <stable version, e.g. 0.1.18>" >&2
  exit 1
fi
tag="v$version"
fail() {
  echo "FAILED: $*" >&2
  exit 1
}
command -v jq >/dev/null || fail "jq is needed"

repo="$(cd "$(dirname "$0")/.." && pwd)"
cd "$repo"
git rev-parse -q --verify "$tag^{commit}" >/dev/null || git fetch --quiet upstream "refs/tags/$tag:refs/tags/$tag" || fail "could not find $tag"
conflicts=""
if git merge-base --is-ancestor "$tag" HEAD; then
  # Already merged. The fork before this update: the first parent of the oldest first-parent commit that has the tag.
  new="$(git rev-parse HEAD)"
  newname="HEAD ${new:0:12}"
  pre="$new"
  while git rev-parse -q --verify "$pre^1" >/dev/null && git merge-base --is-ancestor "$tag" "$pre^1"; do pre="$(git rev-parse "$pre^1")"; done
  pre="$(git rev-parse "$pre^1")"
else
  # Not merged yet: the tree the merge would make (conflicted files keep their markers).
  pre="$(git rev-parse HEAD)"
  status=0
  preview="$(git merge-tree --write-tree --name-only --no-messages HEAD "$tag")" || status=$?
  [[ $status -le 1 ]] || fail "git merge-tree could not preview the merge of $tag"
  new="$(head -1 <<<"$preview")"
  conflicts="$(tail -n +2 <<<"$preview" | sed '/^$/d')"
  newname="the merge preview, tree ${new:0:12}"
fi
cargo_version() { git show "$1:Cargo.toml" | sed -n 's/^version = "\(.*\)"/\1/p' | head -1; }
from="$(cargo_version "$pre")"

out="$repo/.cache/fork-update-$tag"
mkdir -p "$out"
report="$out/clones.md"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# What shipped as <version>: the fork before this update when that's the version it ran, else the
# release tag (copies from older versions came from a release or a fork build near it).
# Prints nothing when neither exists.
base_for() {
  if [[ $1 == "$from" ]]; then echo "$pre"; return; fi
  if git rev-parse -q --verify "v$1^{commit}" >/dev/null || git fetch --quiet upstream "refs/tags/v$1:refs/tags/v$1" 2>/dev/null; then
    echo "v$1"
  fi
}

# Extracts <path> at <commit> into <dir> (left empty when it didn't exist).
extract() {
  mkdir -p "$3"
  git cat-file -e "$1:$2" 2>/dev/null || return 0
  git archive "$1" "$2" | tar -x -C "$3"
}

# A copy's files as comparable text: generated files out, its own name in asset paths back to the original's.
normalize_mod() {
  local src="$1" dst="$2" copy="$3" orig="$4" f rel
  mkdir -p "$dst"
  (cd "$src" && find . -type f ! -name jsconfig.json ! -name '*.d.ts' ! -name .DS_Store ! -path './node_modules/*') | while read -r f; do
    rel="${f#./}"
    mkdir -p "$dst/$(dirname "$rel")"
    if [[ $rel == mod.json ]]; then
      jq -S 'del(.cloned_from)' "$src/$rel" >"$dst/$rel" 2>/dev/null || cp "$src/$rel" "$dst/$rel"
    elif [[ $rel == *.js || $rel == *.json ]]; then
      sed "s#mods/$copy/#mods/$orig/#g" "$src/$rel" >"$dst/$rel"
    else
      cp "$src/$rel" "$dst/$rel"
    fi
  done
}

fence() { printf '\n```diff\n'; cat; printf '```\n'; }

# Names of herdr exports and app commands on lines that changed between $1 and $2.
api_symbols() {
  {
    git diff "$1" "$2" -- defaults/herdr.d.ts | grep -E '^[-+][^-+]' | grep -oE '(function|const|type|class|interface) [A-Za-z_][A-Za-z0-9_]*' | awk '{print $2}' || true
    git diff "$1" "$2" -- src/commands.rs | grep -E '^[-+][^-+]' | grep -oE 'cmd\("[a-z_.]+"' | sed 's/cmd("//; s/"//' || true
  } | sort -u
}

profiles=()
if [[ -n ${HERDR_PROFILES:-} ]]; then read -r -a profiles <<<"$HERDR_PROFILES"; else
  for p in "$HOME/.config/herdr-app" "$HOME/.config/herdr-app-personal"; do [[ -d $p ]] && profiles+=("$p"); done
fi
[[ ${#profiles[@]} -gt 0 ]] || fail "no Herdr profiles found"

shipped_mods="$(git ls-tree --name-only "$new" defaults/mods/ | sed 's#defaults/mods/##')"

{
  echo "# Copies and own mods for the update to $version"
  echo
  echo "Updating from $from (fork commit ${pre:0:12}) to $version ($newname)."
  echo "Generated by scripts/fork-clones.sh; docs/fork-update-copies.md says what to do with it."
  printf '\n## Merge conflicts\n\n'
  if [[ -z $conflicts ]]; then
    echo "None: $tag merges cleanly."
  else
    echo "Fork commits touching a file: \`git log $tag..${pre:0:12} --no-merges -- <file>\`."
    while read -r f; do
      [[ -n $f ]] || continue
      printf '\n### %s\n\nFork side (HEAD) above =======, upstream (%s) below:\n' "$f" "$tag"
      git show "$new:$f" | awk '/^<<<<<<< /{on=1} on{print} /^>>>>>>> /{on=0; print ""}' | fence
    done <<<"$conflicts"
  fi
} >"$report"

affected_total=0
for profile in "${profiles[@]}"; do
  printf '\n## Profile %s\n' "$profile" >>"$report"
  affected=() unaffected=() warnings=() own=()

  # --- Mod copies and own mods (shipped mods are Herdr's and skipped).
  for dir in "$profile"/mods/*/; do
    name="$(basename "$dir")"
    grep -qxF "$name" <<<"$shipped_mods" && continue
    cloned="$(jq -r '.cloned_from // empty | "\(.name) \(.version)"' "$dir/mod.json" 2>/dev/null || true)"
    if [[ -z $cloned ]]; then
      # A copy made by hand: named my-<original> and still starting like it.
      if [[ $name == my-* ]] && grep -qxF "${name#my-}" <<<"$shipped_mods" &&
        [[ "$(head -1 "$dir/main.js" 2>/dev/null)" == "$(git show "$new:defaults/mods/${name#my-}/main.js" 2>/dev/null | head -1)" ]]; then
        warnings+=("mods/$name looks like a copy of ${name#my-} but has no cloned_from: add it to mod.json so it can be checked")
      fi
      own+=("$name")
      continue
    fi
    read -r orig cv <<<"$cloned"
    base="$(base_for "$cv")"
    if [[ -z $base ]]; then warnings+=("mods/$name: no fork commit or tag for $cv (cloned_from.version)"); continue; fi
    if ! git cat-file -e "$new:defaults/mods/$orig" 2>/dev/null && ! git cat-file -e "$base:defaults/mods/$orig" 2>/dev/null; then
      unaffected+=("mods/$name (copy of the person's own mod $orig: nothing shipped to compare)")
    elif ! git cat-file -e "$new:defaults/mods/$orig" 2>/dev/null; then
      affected+=("mod|$name|$orig|$cv|$base|removed")
    elif git diff --quiet "$base" "$new" -- "defaults/mods/$orig"; then
      unaffected+=("mods/$name (copy of $orig, $cv)")
    else
      affected+=("mod|$name|$orig|$cv|$base|changed")
    fi
  done

  # --- Layout copies.
  for f in "$profile"/layouts/*.json; do
    [[ -f $f ]] || continue
    name="$(basename "$f" .json)"
    cloned="$(jq -r '.cloned_from // empty | "\(.name) \(.version)"' "$f" 2>/dev/null || true)"
    [[ -n $cloned ]] || continue
    read -r orig cv <<<"$cloned"
    base="$(base_for "$cv")"
    if [[ -z $base ]]; then warnings+=("layouts/$name.json: no fork commit or tag for $cv (cloned_from.version)"); continue; fi
    if ! git cat-file -e "$new:defaults/layouts/$orig.json" 2>/dev/null && ! git cat-file -e "$base:defaults/layouts/$orig.json" 2>/dev/null; then
      unaffected+=("layouts/$name.json (copy of the person's own layout $orig: nothing shipped to compare)")
    elif ! git cat-file -e "$new:defaults/layouts/$orig.json" 2>/dev/null; then
      affected+=("layout|$name|$orig|$cv|$base|removed")
    elif git diff --quiet "$base" "$new" -- "defaults/layouts/$orig.json"; then
      unaffected+=("layouts/$name.json (copy of $orig, $cv)")
    else
      affected+=("layout|$name|$orig|$cv|$base|changed")
    fi
  done

  affected_total=$((affected_total + ${#affected[@]}))
  printf '\n### Copies whose original changed (%s)\n' "${#affected[@]}" >>"$report"
  [[ ${#affected[@]} -eq 0 ]] && printf '\nNone.\n' >>"$report"
  for a in ${affected[@]+"${affected[@]}"}; do
    IFS='|' read -r kind name orig cv base state <<<"$a"
    work="$tmp/$(basename "$profile")-$kind-$name"
    if [[ $kind == mod ]]; then title="mods/$name"; src="defaults/mods/$orig"; else title="layouts/$name.json"; src="defaults/layouts/$orig.json"; fi
    printf '\n#### %s (copy of %s, cloned_from %s)\n\nBase: %s (%s). New: %s (%s).\n' "$title" "$orig" "$cv" "${base:0:12}" "$cv" "${new:0:12}" "$version" >>"$report"
    if [[ $state == removed ]]; then
      echo "The original no longer exists in $version (removed or renamed). Offer Keep, or Drop if the copy is unused." >>"$report"
      continue
    fi
    {
      printf '\nUpstream change (base → new):\n\n'
      git diff --stat "$base" "$new" -- "$src" | sed 's/^/    /'
      git diff "$base" "$new" -- "$src" | fence
    } >>"$report"
    if [[ $kind == mod ]]; then
      extract "$base" "$src" "$work/base"
      [[ -f "$work/base/$src/mod.json" ]] && jq -S . "$work/base/$src/mod.json" >"$work/mod.json" && mv "$work/mod.json" "$work/base/$src/mod.json"
      normalize_mod "$profile/mods/$name" "$work/copy" "$name" "$orig"
      printf '\nThe copy'"'"'s own changes (base → copy; asset paths and cloned_from normalized):\n' >>"$report"
      (cd "$work" && diff -ru -x jsconfig.json -x '*.d.ts' "base/$src" copy || true) | fence >>"$report"
    else
      mkdir -p "$work"
      git show "$base:$src" | jq -S . >"$work/base.json"
      jq -S 'del(.cloned_from)' "$profile/layouts/$name.json" >"$work/copy.json"
      printf '\nThe copy'"'"'s own changes (base → copy; keys sorted):\n' >>"$report"
      (cd "$work" && diff -u base.json copy.json || true) | fence >>"$report"
    fi
  done

  {
    printf '\n### Copies checked, original unchanged (%s)\n\n' "${#unaffected[@]}"
    [[ ${#unaffected[@]} -eq 0 ]] && echo "None."
    for u in ${unaffected[@]+"${unaffected[@]}"}; do echo "- $u"; done
  } >>"$report"

  # --- Own mods against API changes since the version this profile last ran.
  last="$(jq -r '.last_run // empty' "$profile/update-notes.json" 2>/dev/null || true)"
  [[ -n $last ]] || last="$from"
  apibase="$(base_for "$last")"
  printf '\n### Own mods and API changes (%s → %s)\n\n' "$last" "$version" >>"$report"
  if [[ -z $apibase ]]; then
    echo "No fork commit or tag for $last: compare defaults/herdr.d.ts and src/commands.rs by hand." >>"$report"
  else
    symbols="$(api_symbols "$apibase" "$new")"
    agents_changed=0
    git diff --quiet "$apibase" "$new" -- defaults/AGENTS.md || agents_changed=1
    if [[ -z $symbols && $agents_changed -eq 0 ]]; then
      echo "herdr.d.ts, app commands and AGENTS.md are unchanged." >>"$report"
    else
      {
        echo "Changed herdr exports and app commands: $(echo ${symbols:-none} | tr '\n' ' ')"
        [[ $agents_changed -eq 1 ]] && echo "AGENTS.md changed too: read \`git diff ${apibase:0:12} ${new:0:12} -- defaults/AGENTS.md\` for behavior changes."
        echo
      } >>"$report"
      hits=0
      for name in ${own[@]+"${own[@]}"}; do
        used=""
        for s in $symbols; do
          grep -rqwF --include='*.js' -- "$s" "$profile/mods/$name" 2>/dev/null && used="$used $s"
        done
        [[ -n $used ]] || continue
        hits=$((hits + 1))
        echo "- mods/$name uses:$used" >>"$report"
      done
      [[ $hits -eq 0 ]] && echo "No own mod uses a changed name." >>"$report"
      if ! git diff --quiet "$apibase" "$new" -- defaults/herdr.d.ts; then
        { printf '\nherdr.d.ts diff:\n'; git diff "$apibase" "$new" -- defaults/herdr.d.ts | fence; } >>"$report"
      fi
    fi
  fi

  if [[ ${#warnings[@]} -gt 0 ]]; then
    { printf '\n### Warnings\n\n'; for w in "${warnings[@]}"; do echo "- $w"; done; } >>"$report"
  fi
done

printf '\n## Decisions\n\n_The agent writes Kristoffer'"'"'s answers here, per profile and copy._\n' >>"$report"

echo "$affected_total copies need review, $(grep -c . <<<"$conflicts" || true) files conflict. Report: $report"
